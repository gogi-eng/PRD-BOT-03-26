def detect_type_from_text(filename: str, text: str) -> str:
    """
    Определение вида документа.
    Сначала имя файла и титул (первые абзацы) — они важнее случайных слов в тексте.
    Поэтому «Рабочая инструкция …» никогда не станет «приказом» из‑за слова «приказ» внутри.
    """
    name = (filename or "").lower()
    body = (text or "").lower()
    # титул / шапка — первые ~900 символов
    title = body[:900]
    full = name + "\n" + body[:4000]

    def has_any(blob: str, words: list[str]) -> bool:
        return any(w in blob for w in words)

    # 1) Жёстко по ИМЕНИ ФАЙЛА
    if has_any(name, ["рабочая инструкция", "раб. инструкция", "раб инструкция"]) or (
        ("рабоч" in name or name.startswith("ри ") or " ри " in f" {name} " or name.startswith("ри_"))
        and "инструкц" in name
        and "должностн" not in name
        and "охране труда" not in name
    ):
        return "rabochaya_instrukciya"
    if has_any(name, ["должностная инструкция", "должн. инструкция"]) or (
        (name.startswith("ди ") or name.startswith("ди_") or " ди " in f" {name} ")
        and "инструкц" in name
    ):
        return "dolzhnostnaya_instrukciya"
    if has_any(name, ["инструкция по охране труда", "иот ", " иот_", "по от "]):
        return "instrukciya_ot"
    # инструкция по эксплуатации / производственная — как положение (эталон КЛ)
    if has_any(
        name,
        [
            "инструкция по эксплуатации",
            "по эксплуатации",
            "инструкция по техн",
        ],
    ) or (
        "инструкц" in name
        and "рабоч" not in name
        and "должностн" not in name
        and "охране труда" not in name
        and "иот" not in name
    ):
        return "polozhenie"
    if "положен" in name:
        return "polozhenie"
    if name.startswith("приказ") or " приказ " in f" {name} " or name.startswith("приказ_"):
        return "prikaz"
    # проекты ДИ в САТП: «ПРОЕКТ Старший мастер.docx» — титул часто только в таблице
    if "проект" in name and any(
        w in name for w in ("мастер", "диспетчер", "инженер", "начальник", "экономист", "слесар")
    ):
        return "dolzhnostnaya_instrukciya"

    # 2) По ТИТУЛУ / шапке (важнее середины документа)
    if has_any(title, ["рабочая инструкция", "рабочей инструкции"]):
        return "rabochaya_instrukciya"
    if has_any(title, ["должностная инструкция", "должностной инструкции"]):
        return "dolzhnostnaya_instrukciya"
    if has_any(full, ["старший мастер", "старшего мастера", "ст. мастер"]):
        return "dolzhnostnaya_instrukciya"
    if has_any(title, ["инструкция по охране труда"]):
        return "instrukciya_ot"
    if has_any(
        title,
        [
            "инструкция по эксплуатации",
            "положение о ",
            "настоящее положение",
            "положение\nо ",
        ],
    ):
        return "polozhenie"
    # титул «ИНСТРУКЦИЯ» (не РИ/ДИ/ИОТ) — оформлять по правилам положения/КЛ
    if re.search(r"(?m)^\s*инструкция\b", title) and not has_any(
        title, ["рабочая инструкция", "должностная инструкция", "охране труда"]
    ):
        return "polozhenie"
    # «ПРИКАЗ» как заголовок (отдельной строкой / в начале)
    if re.search(r"(?m)^\s*приказ\s*$", title) or title.lstrip().startswith("приказ\n"):
        return "prikaz"
    if "приказываю" in title:
        return "prikaz"

    # 3) По всему началу текста — сначала более узкие виды
    ordered = [
        ("rabochaya_instrukciya", ["рабочая инструкция", "рабочей инструкции"]),
        ("dolzhnostnaya_instrukciya", ["должностная инструкция", "должностной инструкции"]),
        ("instrukciya_ot", ["инструкция по охране труда", "по охране труда"]),
        (
            "polozhenie",
            [
                "положение о ",
                "настоящее положение",
                "инструкция по эксплуатации",
                "настоящая инструкция",
            ],
        ),
        ("prikaz", ["приказываю"]),  # одно «приказ» в тексте НЕдостаточно
    ]
    for key, words in ordered:
        if has_any(full, words):
            return key

    if "приказ" in name:
        return "prikaz"
    return "unsupported"


def is_instruction_aligned_sample(filename: str) -> bool:
    """Файлы ваших правок — уже с учётом Инструкции / практики СНиОТ."""
    low = (filename or "").lower()
    markers = (
        "сниот",
        "снот",
        "дубовик",
        "исправл",
        "правлен",
        "ред дуб",
        "с правк",
        "образец",
    )
    return any(m in low for m in markers)
